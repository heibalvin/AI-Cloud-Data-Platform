#!/bin/bash
set -e

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    CREATE USER $POSTGRES_AICD_USER WITH PASSWORD '$POSTGRES_AICD_PASSWORD';
    CREATE DATABASE $POSTGRES_AICD_DB OWNER $POSTGRES_AICD_USER;
    GRANT ALL PRIVILEGES ON DATABASE $POSTGRES_AICD_DB TO $POSTGRES_AICD_USER;
    \c $POSTGRES_AICD_DB
    GRANT ALL ON SCHEMA public TO $POSTGRES_AICD_USER;
EOSQL
